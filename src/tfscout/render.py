"""Markdown / JSON rendering of reports."""

from __future__ import annotations

import json
from dataclasses import asdict
from typing import Any

from tfscout import __version__
from tfscout.analyze import DriftReport, ReviewReport

SEV_ICON = {"critical": "🔴", "high": "🟠", "medium": "🟡", "low": "🔵", "info": "⚪"}
ACTION_ICON = {"create": "➕", "update": "✏️", "replace": "♻️", "delete": "🗑️"}
DRIFT_ICON = {"risky": "🔴", "manual-change": "🟡", "noise": "⚪"}
REPO_URL = "https://github.com/mikonoid/tfscout"


def review_marker(name: str) -> str:
    return f"<!-- tfscout:review:{name} -->"


def drift_marker(name: str) -> str:
    return f"<!-- tfscout:drift:{name} -->"


def _esc(s: Any) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def _code(v: Any) -> str:
    if v is None:
        return "–"
    text = json.dumps(v, default=str) if not isinstance(v, str) else v
    return f"`{_esc(text).replace('`', 'ʼ')}`"


def _footer(ai_used: bool, ai_error: str) -> str:
    mode = "rules + AI" if ai_used else "rules only"
    line = f"<sub>Generated by [tfscout]({REPO_URL}) v{__version__} · {mode}"
    if ai_error:
        line += " · ⚠️ AI analysis unavailable"
    return line + "</sub>"


def render_review_md(r: ReviewReport, name: str = "") -> str:
    title = f"### 🔎 tfscout plan review{f' — `{name}`' if name else ''}"
    lines = [review_marker(name or "default"), title, ""]
    if not r.changes:
        lines += ["✅ No changes. Infrastructure matches the configuration.", "", _footer(r.ai_used, r.ai_error)]
        return "\n".join(lines)

    counts = " · ".join(f"{ACTION_ICON[k]} {k} **{v}**" for k, v in r.counts.items() if v)
    lines += [counts, ""]
    if r.summary:
        lines += [r.summary, ""]

    if r.findings:
        lines += ["| | Severity | Resource | Finding |", "|---|---|---|---|"]
        for f in r.findings:
            src = " 🤖" if f.source == "ai" else ""
            lines.append(
                f"| {SEV_ICON.get(f.severity, '')} | {f.severity} | `{_esc(f.resource)}` | {_esc(f.title)}{src} |"
            )
        detailed = [f for f in r.findings if f.detail or f.recommendation]
        if detailed:
            lines += ["", "<details><summary>Details & recommendations</summary>", ""]
            for f in detailed:
                lines.append(f"- **{_esc(f.title)}** (`{f.resource}`)")
                if f.detail:
                    lines.append(f"  - {f.detail}")
                if f.recommendation:
                    lines.append(f"  - 💡 {f.recommendation}")
            lines += ["", "</details>"]
    else:
        lines.append("✅ No risks detected.")

    lines += ["", f"<details><summary>All changes ({len(r.changes)})</summary>", ""]
    for c in r.changes:
        lines.append(f"- {ACTION_ICON.get(c.action, '')} `{c.address}` — {c.action}")
    lines += ["", "</details>", "", _footer(r.ai_used, r.ai_error)]
    return "\n".join(lines)


def render_drift_md(r: DriftReport, name: str = "") -> str:
    title = f"### 🧭 tfscout drift report{f' — `{name}`' if name else ''}"
    lines = [drift_marker(name or "default"), title, ""]
    if not r.items:
        lines += ["✅ No drift detected.", "", _footer(r.ai_used, r.ai_error)]
        return "\n".join(lines)

    by_cls = {k: sum(1 for i in r.items if i.classification == k) for k in DRIFT_ICON}
    lines += [" · ".join(f"{DRIFT_ICON[k]} {k} **{v}**" for k, v in by_cls.items() if v), ""]
    if r.summary:
        lines += [r.summary, ""]

    for i in r.items:
        lines.append(f"#### {DRIFT_ICON[i.classification]} `{i.resource}` — {i.classification}")
        lines.append(i.explanation or i.reason)
        if i.diffs:
            lines += ["", "| Attribute | In state | Real |", "|---|---|---|"]
            lines += [f"| `{_esc(d.path)}` | {_code(d.before)} | {_code(d.after)} |" for d in i.diffs[:25]]
            if len(i.diffs) > 25:
                lines.append(f"| … {len(i.diffs) - 25} more | | |")
        if i.recommendation:
            lines += ["", f"💡 {i.recommendation}"]
        lines.append("")
    lines += [f"<sub>fingerprint: `{r.fingerprint or 'none'}`</sub>", "", _footer(r.ai_used, r.ai_error)]
    return "\n".join(lines)


def review_json(r: ReviewReport) -> str:
    return json.dumps(
        {
            "summary": r.summary,
            "counts": r.counts,
            "max_severity": r.max_severity,
            "findings": [asdict(f) for f in r.findings],
            "changes": [{"address": c.address, "action": c.action} for c in r.changes],
            "ai_used": r.ai_used,
            "ai_error": r.ai_error,
        },
        indent=2,
    )


def drift_json(r: DriftReport) -> str:
    return json.dumps(
        {
            "summary": r.summary,
            "fingerprint": r.fingerprint,
            "items": [
                {
                    "resource": i.resource,
                    "type": i.type,
                    "action": i.action,
                    "classification": i.classification,
                    "reason": i.reason,
                    "explanation": i.explanation,
                    "recommendation": i.recommendation,
                    "diff": [asdict(d) for d in i.diffs],
                }
                for i in r.items
            ],
            "ai_used": r.ai_used,
            "ai_error": r.ai_error,
        },
        indent=2,
        default=str,
    )
