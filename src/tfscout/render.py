"""Markdown / JSON rendering of reports."""

from __future__ import annotations

import json
from dataclasses import asdict
from typing import Any

from tfscout import __version__
from tfscout.analyze import DriftReport, ReviewReport

ACTION_ORDER = ["create", "update", "replace", "delete"]
DRIFT_ORDER = ["risky", "manual-change", "noise"]
REPO_URL = "https://github.com/mikonoid/tfscout"


def review_marker(name: str) -> str:
    return f"<!-- tfscout:review:{name} -->"


def drift_marker(name: str) -> str:
    return f"<!-- tfscout:drift:{name} -->"


def _esc(s: Any) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def _code(v: Any) -> str:
    if v is None:
        return "-"
    text = json.dumps(v, default=str) if not isinstance(v, str) else v
    text = _esc(text).replace("`", "'")
    return f"`{text}`"


def _title(kind: str, name: str) -> str:
    return f"### tfscout {kind}" + (f": `{name}`" if name else "")


def _footer(ai_used: bool, ai_error: str) -> str:
    mode = "rules and AI" if ai_used else "rules only"
    line = f"<sub>Generated by [tfscout]({REPO_URL}) v{__version__}, {mode}"
    if ai_error:
        line += ". AI analysis was unavailable for this run"
    return line + ".</sub>"


def render_review_md(r: ReviewReport, name: str = "") -> str:
    lines = [review_marker(name or "default"), _title("plan review", name), ""]
    if not r.changes:
        lines += ["No changes. Infrastructure matches the configuration.", "", _footer(r.ai_used, r.ai_error)]
        return "\n".join(lines)

    counts = ", ".join(f"{r.counts[k]} to {k}" for k in ACTION_ORDER if r.counts.get(k))
    lines += [f"Plan: {counts}.", ""]
    if r.summary:
        lines += [r.summary, ""]

    if r.findings:
        lines += ["| Severity | Resource | Finding |", "|---|---|---|"]
        for f in r.findings:
            src = " (AI)" if f.source == "ai" else ""
            lines.append(f"| {f.severity} | `{_esc(f.resource)}` | {_esc(f.title)}{src} |")
        detailed = [f for f in r.findings if f.detail or f.recommendation]
        if detailed:
            lines += ["", "<details><summary>Details and recommendations</summary>", ""]
            for f in detailed:
                lines.append(f"- **{_esc(f.title)}** (`{f.resource}`)")
                if f.detail:
                    lines.append(f"  - {f.detail}")
                if f.recommendation:
                    lines.append(f"  - Recommendation: {f.recommendation}")
            lines += ["", "</details>"]
    else:
        lines.append("No risks found.")

    lines += ["", f"<details><summary>All changes ({len(r.changes)})</summary>", ""]
    for c in r.changes:
        lines.append(f"- `{c.address}`: {c.action}")
    lines += ["", "</details>", "", _footer(r.ai_used, r.ai_error)]
    return "\n".join(lines)


def render_drift_md(r: DriftReport, name: str = "") -> str:
    lines = [drift_marker(name or "default"), _title("drift report", name), ""]
    if not r.items:
        lines += ["No drift detected.", "", _footer(r.ai_used, r.ai_error)]
        return "\n".join(lines)

    by_cls = {k: sum(1 for i in r.items if i.classification == k) for k in DRIFT_ORDER}
    lines += [", ".join(f"{v} {k}" for k, v in by_cls.items() if v) + ".", ""]
    if r.summary:
        lines += [r.summary, ""]

    for i in r.items:
        lines += [f"#### `{i.resource}`: {i.classification}", "", i.explanation or i.reason]
        if i.diffs:
            lines += ["", "| Attribute | In state | Actual |", "|---|---|---|"]
            lines += [f"| `{_esc(d.path)}` | {_code(d.before)} | {_code(d.after)} |" for d in i.diffs[:25]]
            if len(i.diffs) > 25:
                lines.append(f"| ... {len(i.diffs) - 25} more | | |")
        if i.recommendation:
            lines += ["", f"Recommendation: {i.recommendation}"]
        lines.append("")
    lines += [f"<sub>fingerprint: `{r.fingerprint or 'none'}`</sub>", "", _footer(r.ai_used, r.ai_error)]
    return "\n".join(lines)


def review_json(r: ReviewReport) -> str:
    return json.dumps(
        {
            "summary": r.summary,
            "counts": r.counts,
            "max_severity": r.max_severity,
            "findings": [asdict(f) for f in r.findings],
            "changes": [{"address": c.address, "action": c.action} for c in r.changes],
            "ai_used": r.ai_used,
            "ai_error": r.ai_error,
        },
        indent=2,
    )


def drift_json(r: DriftReport) -> str:
    return json.dumps(
        {
            "summary": r.summary,
            "fingerprint": r.fingerprint,
            "items": [
                {
                    "resource": i.resource,
                    "type": i.type,
                    "action": i.action,
                    "classification": i.classification,
                    "reason": i.reason,
                    "explanation": i.explanation,
                    "recommendation": i.recommendation,
                    "diff": [asdict(d) for d in i.diffs],
                }
                for i in r.items
            ],
            "ai_used": r.ai_used,
            "ai_error": r.ai_error,
        },
        indent=2,
        default=str,
    )
